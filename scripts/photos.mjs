// Writes apps/app/src/photos.ts: a require() for every photo in apps/app/assets/photos, so Metro bundles them and a
// missing photo is simply absent (the app then draws a fire-coloured tile). Run after adding or removing photos.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

process.chdir(fileURLToPath(new URL('..', import.meta.url)));
const dir = 'apps/app/assets/photos';
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort() : [];
const lines = files.map((f) => `  '${f.replace(/\.[^.]+$/, '')}': require('../assets/photos/${f}'),`);
fs.writeFileSync(
  'apps/app/src/photos.ts',
  `// Generated by scripts/photos.mjs from apps/app/assets/photos; sources in apps/app/assets/photos/CREDITS.md.\n/* eslint-disable @typescript-eslint/no-require-imports */\nexport const PHOTOS: Record<string, number> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`photos.ts: ${files.length} photos`);
